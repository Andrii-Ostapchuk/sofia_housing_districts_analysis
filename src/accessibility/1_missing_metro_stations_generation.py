# to merge all metro lines into one flat dictionary for the sjoin buffer script:
all_stations = {**stations_m1, **stations_m2, **stations_m3, **stations_m4}

features = []
radius = 800

# 2. Project to UTM Zone 34N (EPSG:32634) to buffer accurately in meters
for name, coords in all_stations.items():
    # Create point in WGS84 and convert to projected meters
    pt_wgs84 = gpd.GeoSeries([Point(coords[0], coords[1])], crs="EPSG:4326")
    pt_proj = pt_wgs84.to_crs("EPSG:32634").iloc[0]
    
    # Create 800m buffer polygon
    buf_proj = pt_proj.buffer(radius)
    
    # Convert back to WGS84 (EPSG:4326) so it matches standard GeoJSON format
    buf_wgs84 = gpd.GeoSeries([buf_proj], crs="EPSG:32634").to_crs("EPSG:4326").iloc[0]
    
    # Explicitly cast to MultiPolygon to match your other dataset types
    multi_poly = MultiPolygon([buf_wgs84])
    
    feature = {
        "type": "Feature",
        "geometry": mapping(multi_poly),
        "properties": {
            "station_name": name,
            "tobreak": float(radius)
        }
    }
    features.append(feature)

geojson_output = {
    "type": "FeatureCollection",
    "features": features
}

# 3. Save to file
